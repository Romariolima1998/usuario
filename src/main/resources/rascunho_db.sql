
    create table endereco (
        estado varchar(2),
        id bigint generated by default as identity,
        numero bigint,
        usuario_id bigint,
        cep varchar(9),
        complemento varchar(10),
        cidade varchar(150),
        rua varchar(255),
        primary key (id)
    );

    create table telefone (
        ddd varchar(3),
        id bigint generated by default as identity,
        usuario_id bigint,
        numero varchar(11),
        primary key (id)
    );

    create table usuario (
        id bigint generated by default as identity,
        email varchar(100),
        nome varchar(100),
        senha varchar(255),
        primary key (id)
    );

